export const BENGALI_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯']
export const HINDI_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९']

export function toBengaliNumerals(value) {
  if (value === null || value === undefined) return ''
  return String(value).replace(/[0-9]/g, digit => BENGALI_DIGITS[parseInt(digit, 10)])
}

export function toHindiNumerals(value) {
  if (value === null || value === undefined) return ''
  return String(value).replace(/[0-9]/g, digit => HINDI_DIGITS[parseInt(digit, 10)])
}
